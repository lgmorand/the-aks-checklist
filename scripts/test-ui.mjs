import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { loadChecklist, readJson, fromRoot } from './lib.mjs';
import { startPreview } from './preview.mjs';

const { items, sections } = await loadChecklist();
const preview = await startPreview();
let browser;
let assertions = 0;
const check = (condition, label) => { assert.ok(condition, label); assertions++; };
try {
  browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: 'light', reducedMotion: 'reduce', acceptDownloads: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(preview.url);
  check(await page.locator('.check-item').count() === items.length, 'all checklist items rendered');
  check(await page.locator('.checklist-section').count() === sections.length, 'all sections rendered');
  check(await page.locator('html').getAttribute('data-theme') === 'light', 'system light theme');
  await page.locator('#theme-toggle').click();
  check(await page.locator('html').getAttribute('data-theme') === 'dark', 'theme toggle');
  check(await page.locator('#theme-toggle').getAttribute('aria-label') === 'Switch to light theme', 'theme accessible name');
  await page.reload();
  check(await page.locator('html').getAttribute('data-theme') === 'dark', 'theme persists');
  await page.locator('#project-name').fill('Platform production review');
  await page.locator('#review-owner').fill('Cloud engineering');
  const first = page.locator('.check-item').first();
  await first.locator('.item-check').check();
  check((await page.locator('#progress-summary').textContent()).startsWith('1 of '), 'completion updates');
  await first.locator('summary').click();
  await first.locator('.evidence').fill('Validated with workload owner');
  await first.locator('.item-na').check();
  check(await first.locator('.item-check').isDisabled(), 'N/A excludes completion');
  check((await page.locator('#progress-summary').textContent()).includes('1 not applicable'), 'N/A reflected in progress');
  await page.reload();
  check(await page.locator('#project-name').inputValue() === 'Platform production review', 'project persists');
  await first.locator('summary').click();
  check(await first.locator('.evidence').inputValue() === 'Validated with workload owner', 'evidence persists');
  await first.locator('.item-na').uncheck();
  await page.locator('#search').fill('kubenet');
  check(await page.locator('.check-item:visible').count() > 0, 'search finds lifecycle guidance');
  await page.locator('#priority-filter').selectOption('High');
  check(await page.locator('.check-item:visible').evaluateAll((els) => els.every((el) => el.dataset.priority === 'High')), 'priority filter combines with search');
  await page.locator('#tag-filter').selectOption('lifecycle');
  check(await page.locator('.check-item:visible').evaluateAll((els) => els.every((el) => el.dataset.tags.split(' ').includes('lifecycle'))), 'tag filter combines with search');
  await page.locator('#search').fill('no-such-check-928731');
  check(await page.locator('#empty-state').isVisible(), 'empty search result');
  await page.locator('#search').fill('');
  await page.locator('#priority-filter').selectOption('all');
  await page.locator('#tag-filter').selectOption('all');
  await page.locator('#section-architecture [data-action="complete"]').click();
  check(await page.locator('#section-architecture .item-check:checked').count() === sections[0].items.length, 'complete section');
  await page.locator('#status-filter').selectOption('complete');
  check(await page.locator('.check-item:visible').count() === sections[0].items.length, 'completion filter');
  await page.locator('#expand-all').click();
  check(await page.locator('.check-item:visible details:not([open])').count() === 0, 'expand visible details');
  await page.locator('#collapse-all').click();
  check(await page.locator('.check-item:visible details[open]').count() === 0, 'collapse visible details');
  await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')));
  check(await page.locator('.check-item[hidden]').count() === 0, 'printed report includes filtered-out items');
  check(await page.locator('.item-details:not([open])').count() === 0, 'printed report expands all references');
  check((await first.locator('.print-only').textContent()).includes('Validated with workload owner'), 'printed evidence is emitted as wrapping text');
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
  check(await page.locator('.check-item:visible').count() === sections[0].items.length, 'print restores filters');
  const downloadEvent = page.waitForEvent('download');
  await page.locator('#export-review').click();
  const download = await downloadEvent;
  const stream = await download.createReadStream();
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  check(exported.completed.length === sections[0].items.length && exported.owner === 'Cloud engineering', 'review export includes state and metadata');
  page.on('dialog', (dialog) => dialog.accept());
  await page.locator('#reset-review').click();
  check(await page.locator('.item-check:checked').count() === 0, 'reset review');
  await page.locator('#review-file').setInputFiles({ name: 'review.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(exported)) });
  await page.waitForFunction(() => document.querySelectorAll('.item-check:checked').length > 0);
  check(await page.locator('#review-owner').inputValue() === 'Cloud engineering', 'review import restores state');
  await page.locator('#review-file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{"version":1}') });
  await page.waitForFunction(() => document.querySelector('#storage-message').textContent.includes('could not be imported'));
  check((await page.locator('#storage-message').textContent()).includes('Unsupported review file'), 'invalid import reports explicit error');
  for (const link of ['AKS-Checklist.pdf', 'AKS-Checklist.docx', 'AKS-Checklist.html']) {
    const response = await page.request.get(`${preview.url}/docs/${link}`);
    check(response.status() === 200 && (await response.body()).length > 10000, `${link} download exists`);
  }
  for (const width of [1440, 800, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await page.locator('#status-filter').selectOption('all');
    await page.evaluate(() => window.scrollTo(0, 0));
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `no horizontal overflow at ${width}px`);
    check(await page.locator('#theme-toggle').isVisible(), `theme toggle at ${width}px`);
  }
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  await page.evaluate(() => localStorage.removeItem('aks-checklist-theme'));
  await page.reload();
  check(await page.locator('html').getAttribute('data-theme') === 'dark', 'system dark theme');
  check(errors.length === 0, `no browser errors: ${errors.join('; ')}`);
  const legacy = await readJson('data', 'en', 'project', 'legacy-progress.json');
  const migrated = await browser.newContext();
  await migrated.addInitScript(() => localStorage.setItem('cluster-security', JSON.stringify([{ id: '0' }])));
  const migratedPage = await migrated.newPage();
  await migratedPage.goto(preview.url);
  check(await migratedPage.locator(`#check-${legacy['cluster-security'][0]}`).isChecked(), 'legacy progress migrates across moved sections');
  const disabled = await browser.newContext({ javaScriptEnabled: false });
  const noJs = await disabled.newPage();
  await noJs.goto(preview.url);
  check(await noJs.locator('.check-item').count() === items.length, 'guidance remains available without JavaScript');
  check(await noJs.locator('noscript').isVisible(), 'no-JavaScript notice');
  check((await page.request.get(`${preview.url}/not-a-file`)).status() === 404, 'missing resources return explicit 404');
  const unavailableStorage = await browser.newContext();
  await unavailableStorage.addInitScript(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Storage denied', 'QuotaExceededError'); };
  });
  const deniedPage = await unavailableStorage.newPage();
  await deniedPage.goto(preview.url);
  await deniedPage.locator('.item-check').first().check();
  check((await deniedPage.locator('#storage-message').textContent()).includes('could not save'), 'storage failure is surfaced');
  check(await deniedPage.locator('.item-check').first().isChecked(), 'storage failure preserves in-memory review');
  console.log(`Passed ${assertions} UI assertions: state, migration, filters, theme, print, imports, downloads, responsive layout, and no-JS rendering.`);
} finally {
  if (browser) await browser.close();
  await preview.close();
}
